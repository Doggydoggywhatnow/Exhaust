/* Reads docs/formats.md and writes the C tables of what it defines, so the document is the only
 * place a name is defined: the settings (the tables between "## settings.ini" and "## hotkeys.ini")
 * and the commands (the table under "## Commands").
 * Usage: gen_tables FORMATS.MD SETTINGS.C COMMANDS.C */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static char *dupstr(const char *s) { size_t n = strlen(s); char *p = malloc(n + 1); if (p) memcpy(p, s, n + 1); return p; }

static char *read_all(const char *path, size_t *len) {
    FILE *f = fopen(path, "rb");
    char *buf;
    long n;
    if (!f) return NULL;
    fseek(f, 0, SEEK_END);
    n = ftell(f);
    fseek(f, 0, SEEK_SET);
    buf = malloc((size_t)n + 1);
    if (!buf) { fclose(f); return NULL; }
    *len = fread(buf, 1, (size_t)n, f);
    buf[*len] = 0;
    fclose(f);
    return buf;
}

/* Splits a table row into cells; "\|" inside a cell is a literal bar. Returns the number of cells. */
static int cells(char *line, char **out, int max) {
    int n = 0;
    char *p = line;
    if (*p == '|') p++;
    while (*p && n < max) {
        char *w = p, *start = p;
        while (*p && !(*p == '|')) { if (*p == '\\' && p[1] == '|') { *w++ = '|'; p += 2; } else *w++ = *p++; }
        if (*p == '|') p++;
        else if (!*p && w == start) break;
        *w = 0;
        while (*start == ' ') start++;
        { char *e = start + strlen(start); while (e > start && e[-1] == ' ') *--e = 0; }
        out[n++] = start;
    }
    return n;
}

static void c_string(FILE *o, const char *s) {
    fputc('"', o);
    for (; *s; s++) { if (*s == '"' || *s == '\\') fputc('\\', o); fputc(*s, o); }
    fputc('"', o);
}

/* The text inside the first pair of backticks, or NULL. */
static char *backticked(char *s) {
    char *a = strchr(s, '`'), *b;
    if (!a) return NULL;
    b = strchr(a + 1, '`');
    if (!b) return NULL;
    *b = 0;
    return a + 1;
}

static int gen_settings(const char *doc, const char *out) {
    char *text = dupstr(doc), *start, *end, *line, *next, section[64] = "";
    FILE *o;
    int count = 0;
    start = strstr(text, "\n## settings.ini");
    end = strstr(text, "\n## hotkeys.ini");
    if (!start || !end || end < start) { fprintf(stderr, "settings section not found\n"); return 1; }
    *end = 0;
    o = fopen(out, "wb");
    if (!o) return 1;
    fputs("/* Generated by tools/gen_tables from docs/formats.md. Do not edit. */\n#include \"exhaust_settings.h\"\n\nconst ExSettingDef ex_settings_schema[] = {\n", o);
    for (line = start + 1; line; line = next) {
        next = strchr(line, '\n');
        if (next) *next++ = 0;
        if (strncmp(line, "### [", 5) == 0) {
            char *close = strchr(line + 5, ']');
            if (close) { *close = 0; snprintf(section, sizeof section, "%s", line + 5); }
            continue;
        }
        if (line[0] == '|' && section[0] && strstr(line, "| `")) {
            char *c[8], copy[2048];
            int n;
            snprintf(copy, sizeof copy, "%s", line);
            n = cells(copy, c, 8);
            if (n >= 3 && c[0][0] == '`') {
                char *key = backticked(c[0]), *type = c[1], *def, enumv[512] = "", tname[16];
                char defbuf[512] = "";
                int stub = strstr(c[2], "(stub)") != NULL, is_enum = 0;
                if (!key) continue;
                if (strncmp(type, "enum(", 5) == 0) {
                    char *close = strrchr(type, ')');
                    if (close) { *close = 0; snprintf(enumv, sizeof enumv, "%s", type + 5); }
                    is_enum = strstr(enumv, "...") == NULL;
                    snprintf(tname, sizeof tname, "%s", is_enum ? "EX_SET_ENUM" : "EX_SET_STRING");
                } else if (!strcmp(type, "bool")) snprintf(tname, sizeof tname, "EX_SET_BOOL");
                else if (!strcmp(type, "int")) snprintf(tname, sizeof tname, "EX_SET_INT");
                else if (!strcmp(type, "percent")) snprintf(tname, sizeof tname, "EX_SET_PERCENT");
                else if (!strcmp(type, "path")) snprintf(tname, sizeof tname, "EX_SET_PATH");
                else if (!strcmp(type, "color")) snprintf(tname, sizeof tname, "EX_SET_COLOR");
                else if (!strcmp(type, "list")) snprintf(tname, sizeof tname, "EX_SET_LIST");
                else snprintf(tname, sizeof tname, "EX_SET_STRING");
                snprintf(defbuf, sizeof defbuf, "%s", c[2]);
                def = backticked(defbuf);
                fprintf(o, "    {");
                c_string(o, section); fprintf(o, ", "); c_string(o, key); fprintf(o, ", %s, ", tname);
                c_string(o, def ? def : ""); fprintf(o, ", ");
                if (is_enum) c_string(o, enumv); else fprintf(o, "0");
                fprintf(o, ", %d},\n", stub);
                count++;
            }
        }
    }
    fprintf(o, "};\n\nconst size_t ex_settings_schema_count = %d;\n", count);
    fclose(o);
    free(text);
    return count > 0 ? 0 : 1;
}

static int gen_commands(const char *doc, const char *out) {
    char *text = dupstr(doc), *start, *end, *line, *next;
    FILE *o;
    int count = 0;
    start = strstr(text, "\n## Commands");
    if (!start) { fprintf(stderr, "commands section not found\n"); return 1; }
    end = strstr(start + 3, "\n## ");
    if (end) *end = 0;
    o = fopen(out, "wb");
    if (!o) return 1;
    fputs("/* Generated by tools/gen_tables from docs/formats.md. Do not edit. */\n#include \"exhaust_commands.h\"\n\nconst ExCommandDef ex_command_table[] = {\n", o);
    for (line = start + 1; line; line = next) {
        next = strchr(line, '\n');
        if (next) *next++ = 0;
        if (line[0] == '|' && strstr(line, "| `")) {
            char *c[8], copy[2048], *id, *def;
            int n;
            snprintf(copy, sizeof copy, "%s", line);
            n = cells(copy, c, 8);
            if (n >= 4 && c[0][0] == '`' && (id = backticked(c[0])) != NULL) {
                char defbuf[256] = "";
                snprintf(defbuf, sizeof defbuf, "%s", c[2]);
                def = backticked(defbuf);
                fprintf(o, "    {"); c_string(o, id); fprintf(o, ", "); c_string(o, c[1]); fprintf(o, ", "); c_string(o, def ? def : "");
                fprintf(o, ", %d},\n", strcmp(c[3], "yes") == 0);
                count++;
            }
        }
    }
    fprintf(o, "};\n\nconst size_t ex_command_table_count = %d;\n", count);
    fclose(o);
    free(text);
    return count > 0 ? 0 : 1;
}

int main(int argc, char **argv) {
    size_t len;
    char *doc;
    int rc;
    if (argc != 4) { fprintf(stderr, "usage: gen_tables FORMATS.MD SETTINGS.C COMMANDS.C\n"); return 2; }
    doc = read_all(argv[1], &len);
    if (!doc) { fprintf(stderr, "cannot read %s\n", argv[1]); return 1; }
    rc = gen_settings(doc, argv[2]);
    if (rc == 0) rc = gen_commands(doc, argv[3]);
    free(doc);
    return rc;
}
