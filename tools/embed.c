/* Build-time tool: turns binary files into C arrays.
 * Usage: embed <output.c> <symbol> <input> [<symbol> <input> ...]
 * Writes `const unsigned char <symbol>[]` and `const unsigned long <symbol>_len`.
 * Used by CMake to embed the built-in fonts, so the core build needs no
 * downloads and no scripting language. */
#include <stdio.h>
#include <stdlib.h>

int main(int argc, char **argv) {
    FILE *out;
    int a;
    if (argc < 4 || (argc - 2) % 2 != 0) {
        fprintf(stderr, "usage: embed <output.c> <symbol> <input> ...\n");
        return 2;
    }
    out = fopen(argv[1], "wb");
    if (!out) { perror(argv[1]); return 1; }
    fprintf(out, "/* Generated by tools/embed.c. Do not edit. */\n");
    for (a = 2; a + 1 < argc; a += 2) {
        FILE *in = fopen(argv[a + 1], "rb");
        unsigned long n = 0;
        int c;
        if (!in) { perror(argv[a + 1]); fclose(out); return 1; }
        fprintf(out, "const unsigned char %s[] = {", argv[a]);
        while ((c = fgetc(in)) != EOF) {
            if (n % 24 == 0) fputs("\n", out);
            fprintf(out, "%d,", c);
            n++;
        }
        fclose(in);
        fprintf(out, "\n0};\nconst unsigned long %s_len = %luUL;\n", argv[a], n);
    }
    return fclose(out) ? 1 : 0;
}
